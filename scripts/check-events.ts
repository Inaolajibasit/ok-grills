import assert from "node:assert/strict";
import { eventPackages } from "../src/data/event-packages";
import { siteSettings } from "../src/data/site-settings";
import { createEventEnquirySchema, formatEventEnquiry, getEnquiryWhatsAppUrl, getEventToday, type EventEnquiryInput } from "../src/lib/event-enquiry";

const schema = createEventEnquirySchema(eventPackages.map((entry) => entry.id), siteSettings.events.eventTypes);
const fixture: EventEnquiryInput = { name: "  Ayo Test  ", phone: "+2348101234567", eventType: "Wedding", eventDate: "2096-02-29", guestCount: "150", deliveryArea: "Lekki", budget: "₦800,000 — flexible", foodPreferences: "Turkey & ribs\nSauce separately", additionalNotes: "Garden venue + live music", packageId: "function" };
const parsed = schema.parse(fixture);
assert.equal(parsed.name, "Ayo Test");
assert.equal(parsed.guestCount, 150);
assert.equal(eventPackages.length, 3);
assert.ok(eventPackages.every((entry) => entry.price === null && entry.minimumGuests === undefined && entry.maximumGuests === undefined));
for (const guestCount of ["0", "-1", "1.5", "1e3", "9007199254740992", ""]) assert.equal(schema.safeParse({ ...fixture, guestCount }).success, false);
for (const eventDate of ["2020-01-01", "2096-02-30", "2097-02-29", "tomorrow", ""]) assert.equal(schema.safeParse({ ...fixture, eventDate }).success, false);
for (const phone of ["abc", "123", "+23412345678901234567", "23481hello9288279"]) assert.equal(schema.safeParse({ ...fixture, phone }).success, false);
assert.equal(schema.safeParse({ ...fixture, eventType: "Unknown" }).success, false);
assert.equal(schema.safeParse({ ...fixture, packageId: "Unknown" }).success, false);
assert.equal(schema.safeParse({ ...fixture, deliveryArea: "" }).success, false);
assert.equal(schema.safeParse({ ...fixture, name: "" }).success, false);
assert.equal(schema.safeParse({ ...fixture, additionalNotes: "a".repeat(1501) }).success, false);
assert.equal(getEventToday(new Date("2026-10-05T23:30:00Z")), "2026-10-06", "Dates follow Lagos, including midnight rollover");
const message = formatEventEnquiry(parsed, eventPackages, siteSettings.businessName);
for (const value of ["Ayo Test", fixture.phone, "Wedding", "29 February 2096", "150", "Lekki", "THE FUNCTION", fixture.budget, fixture.foodPreferences, fixture.additionalNotes]) assert.ok(message.includes(value));
const url = getEnquiryWhatsAppUrl(siteSettings.whatsappNumber, message);
assert.ok(url);
const encoded = new URL(url);
assert.equal(encoded.hostname, "wa.me");
assert.equal(encoded.pathname, "/2348109288279");
assert.equal(encoded.searchParams.get("text"), message, "Unicode, ampersands, plus signs and line breaks survive the handoff");
assert.equal([...encoded.searchParams].length, 1);
for (const number of ["", "hello", "https://evil.invalid", "0123456789", "+234 8109288279"]) assert.equal(getEnquiryWhatsAppUrl(number, message), null);
const optional = schema.parse({ ...fixture, packageId: "", budget: "", foodPreferences: "", additionalNotes: "" });
const fallback = formatEventEnquiry(optional, eventPackages, siteSettings.businessName);
assert.ok(fallback.includes("Package: Please recommend"));
assert.ok(fallback.includes("Budget: To discuss"));
console.log("Event checks passed: required fields, guest bounds, real/future dates, Lagos timezone, phone validation, package/type validation, optional values, approved recipient, and lossless WhatsApp encoding.");
