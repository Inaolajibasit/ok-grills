import assert from "node:assert/strict";
import { products } from "../src/data/products";
import { buildBoxSections } from "../src/data/build-your-box";
import { siteSettings } from "../src/data/site-settings";
import { addCartProduct, addCartBuildBox, changeCartQuantity, resolveCartLines } from "../src/lib/cart";
import { checkoutSchema } from "../src/lib/checkout";
import { canContinueOrder, createOrderWhatsAppMessage, createWhatsAppUrl } from "../src/lib/whatsapp";

const details = { customerName: " Ayo & Friends ", phoneNumber: "+2348101234567", area: "Lekki", address: "12 Test Road, Apt 4\nGate on the left", preferredDeliveryTime: "Tomorrow around 5pm", orderNotes: "Call on arrival + sauce separately" };
const parsed = checkoutSchema.parse(details);
assert.equal(parsed.customerName, "Ayo & Friends");
for (const key of ["customerName", "phoneNumber", "area", "address", "preferredDeliveryTime"] as const) assert.equal(checkoutSchema.safeParse({ ...details, [key]: "" }).success, false);
assert.equal(checkoutSchema.safeParse({ ...details, phoneNumber: "123abc" }).success, false);
assert.equal(checkoutSchema.safeParse({ ...details, orderNotes: "a".repeat(1001) }).success, false);
assert.equal(checkoutSchema.safeParse({ ...details, orderNotes: "" }).success, true);
const mini = products.find((product) => product.id === "mini-grill-box");
assert.ok(mini);
const choices = [{ optionId: "grill-choice", choiceIds: ["turkey"] }];
let items = addCartProduct([], mini, choices, "No pepper");
items = addCartProduct(items, mini, choices, "No pepper");
items = addCartBuildBox(items, buildBoxSections, [{ sectionId: "grills", itemId: "turkey", quantity: 2 }, { sectionId: "sides", itemId: "fries", quantity: 1 }], "Sauce separately");
const lines = resolveCartLines(items, products, buildBoxSections);
assert.equal(canContinueOrder(lines), true);
const message = createOrderWhatsAppMessage(lines, parsed, siteSettings.businessName, siteSettings.checkout.confirmationNotice);
for (const value of ["2 × Mini Grill Box", "1 × Custom grill box", "Options per item:", "Ingredients per box:", "Grills: 2 × Grilled Turkey", "Sides: 1 × Fries", "No pepper", "Sauce separately", "54,000", parsed.customerName, parsed.phoneNumber, parsed.area, parsed.address, parsed.preferredDeliveryTime, parsed.orderNotes, "Delivery cost: To be confirmed", "No payment has been taken"]) assert.ok(message.includes(value), `Message includes ${value}`);
const url = createWhatsAppUrl(siteSettings.whatsappNumber, message);
assert.ok(url);
const encoded = new URL(url);
assert.equal(encoded.hostname, "wa.me");
assert.equal(encoded.pathname, "/2348109288279");
assert.equal(encoded.searchParams.get("text"), message);
assert.equal([...encoded.searchParams].length, 1);
assert.equal(createWhatsAppUrl("", message), null);
assert.equal(createWhatsAppUrl("https://invalid.test", message), null);
assert.equal(canContinueOrder([]), false);
assert.throws(() => createOrderWhatsAppMessage([], parsed, "OK Grills", siteSettings.checkout.confirmationNotice));
const missing = resolveCartLines(items, [], []);
assert.equal(canContinueOrder(missing), false);
assert.throws(() => createOrderWhatsAppMessage(missing, parsed, "OK Grills", siteSettings.checkout.confirmationNotice));
assert.equal(canContinueOrder([{ ...lines[0], lineTotal: 1 }]), false);
assert.equal(canContinueOrder([{ ...lines[0], unitPrice: null, lineTotal: null }]), false);
assert.equal(canContinueOrder([{ ...lines[0], item: { ...lines[0].item, quantity: -1 } }]), false);
assert.throws(() => createOrderWhatsAppMessage(lines, { ...parsed, customerName: "" }, "OK Grills", siteSettings.checkout.confirmationNotice));
const updated = resolveCartLines(changeCartQuantity(items, items[0].id, 1), products, buildBoxSections);
assert.ok(createOrderWhatsAppMessage(updated, parsed, siteSettings.businessName, siteSettings.checkout.confirmationNotice).includes("73,000"), "Fresh cart edits are reflected in the message");
const repriced = products.map((product) => product.id === mini.id ? { ...product, price: 20000 } : product);
assert.ok(createOrderWhatsAppMessage(resolveCartLines(items, repriced, buildBoxSections), parsed, siteSettings.businessName, siteSettings.checkout.confirmationNotice).includes("56,000"), "Current catalog prices are used");
console.log("Checkout checks passed: Zod delivery validation, product/options/notes and custom-box metadata, subtotal, changed cart/catalog prices, blocked empty/unpriced/invalid carts, confirmation language, recipient, and lossless WhatsApp encoding.");
